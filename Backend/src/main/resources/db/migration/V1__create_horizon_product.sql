CREATE TABLE horizon_product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference VARCHAR(80) NOT NULL,
    name VARCHAR(150) NOT NULL,
    category VARCHAR(100) NOT NULL,
    price NUMERIC(15, 2) NOT NULL,
    CONSTRAINT uk_horizon_product_reference UNIQUE (reference),
    CONSTRAINT ck_horizon_product_price CHECK (price >= 0),
    CONSTRAINT ck_horizon_product_reference CHECK (length(trim(reference)) > 0),
    CONSTRAINT ck_horizon_product_name CHECK (length(trim(name)) > 0)
);
