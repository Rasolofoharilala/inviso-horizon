CREATE TABLE lot_movement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lot_id BIGINT NOT NULL REFERENCES livestock_lot(id),
    request_id UUID NOT NULL,
    movement_type VARCHAR(20) NOT NULL CHECK (movement_type IN ('ENTRY', 'MORTALITY', 'SALE', 'EXIT')),
    effective_date DATE NOT NULL,
    male_delta BIGINT NOT NULL CHECK (male_delta BETWEEN -2147483647 AND 2147483647),
    female_delta BIGINT NOT NULL CHECK (female_delta BETWEEN -2147483647 AND 2147483647),
    reason VARCHAR(500) NOT NULL CHECK (btrim(reason) <> ''),
    recorded_at TIMESTAMPTZ NOT NULL,
    recorded_by VARCHAR(80) NOT NULL,
    cancelled_at TIMESTAMPTZ,
    cancelled_by VARCHAR(80),
    cancellation_reason VARCHAR(500),
    UNIQUE (lot_id, request_id),
    CHECK (male_delta <> 0 OR female_delta <> 0),
    CHECK ((movement_type = 'ENTRY' AND male_delta >= 0 AND female_delta >= 0)
        OR (movement_type <> 'ENTRY' AND male_delta <= 0 AND female_delta <= 0))
);
CREATE INDEX lot_movement_history_idx ON lot_movement(lot_id, effective_date, id);
